
"""
# tools/dashboard_tools.py
Grafana dashboard tools for creation and deployment
Supports both Prometheus and PostgreSQL datasources
"""

import logging
from typing import Dict, Optional, Any
import aiohttp
import json
import hashlib

logger = logging.getLogger(__name__)


class GrafanaClient:
    """
    Grafana API client for dashboard operations
    """
    
    def __init__(self, grafana_url: str, api_key: str):
        """
        Initialize Grafana client
        
        Args:
            grafana_url: Grafana server URL
            api_key: Grafana API key with dashboards:write permission
        """
        self.base_url = grafana_url.rstrip('/')
        self.api_key = api_key
        self.headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }
        logger.info(f"Grafana client initialized for {self.base_url}")
    
    
    async def test_connection(self) -> bool:
        """
        Test Grafana API connection
        
        Returns:
            True if connection successful
        """
        url = f"{self.base_url}/api/datasources"
        
        try:
            async with aiohttp.ClientSession() as session:
                async with session.get(url, headers=self.headers, timeout=aiohttp.ClientTimeout(total=5)) as response:
                    return response.status == 200
        except Exception as e:
            logger.error(f"Grafana connection test failed: {e}")
            return False
    
    
    async def fetch_datasources(self) -> list[Dict]:
        """
        Fetch all datasources from Grafana
        
        Returns:
            List of datasource configurations
        """
        url = f"{self.base_url}/api/datasources"
        
        try:
            async with aiohttp.ClientSession() as session:
                async with session.get(url, headers=self.headers) as response:
                    if response.status == 200:
                        datasources = await response.json()
                        
                        # Process and filter supported datasources
                        processed = []
                        for ds in datasources:
                            ds_type = ds.get('type', '').lower()
                            
                            if ds_type in ['prometheus', 'postgres', 'loki']:
                                processed.append({
                                    'uid': ds.get('uid', ''),
                                    'name': ds_type,
                                    'type': ds_type,
                                    'url': ds.get('url', ''),
                                    'database': ds.get('database', ''),
                                    'grafana_id': ds.get('id')
                                })
                        
                        logger.info(f"Fetched {len(processed)} datasources from Grafana")
                        return processed
                    else:
                        logger.error(f"Failed to fetch datasources: HTTP {response.status}")
                        return []
        
        except Exception as e:
            logger.error(f"Error fetching datasources: {e}")
            return []
    
    
    async def create_dashboard(
        self,
        dashboard_json: Dict,
        folder_id: int = 0,
        overwrite: bool = True
    ) -> Dict:
        """
        Create or update Grafana dashboard
        
        Args:
            dashboard_json: Dashboard JSON specification
            folder_id: Folder ID (0 = General)
            overwrite: Whether to overwrite existing dashboard
        
        Returns:
            API response with dashboard URL
        """
        url = f"{self.base_url}/api/dashboards/db"
        
        payload = {
            "dashboard": dashboard_json,
            "folderId": folder_id,
            "overwrite": overwrite,
            "message": "Auto-generated by VizGenie"
        }
        
        try:
            async with aiohttp.ClientSession() as session:
                async with session.post(
                    url,
                    json=payload,
                    headers=self.headers,
                    timeout=aiohttp.ClientTimeout(total=30)
                ) as response:
                    if response.status == 200:
                        result = await response.json()
                        dashboard_url = f"{self.base_url}{result.get('url', '')}"
                        
                        logger.info(f"Dashboard created successfully: {dashboard_url}")
                        
                        return {
                            'success': True,
                            'url': dashboard_url,
                            'uid': result.get('uid'),
                            'id': result.get('id'),
                            'version': result.get('version')
                        }
                    else:
                        error_text = await response.text()
                        logger.error(f"Dashboard creation failed: HTTP {response.status} - {error_text}")
                        return {
                            'success': False,
                            'error': f"API Error {response.status}",
                            'details': error_text
                        }
        
        except Exception as e:
            logger.error(f"Dashboard creation exception: {e}")
            return {
                'success': False,
                'error': str(e)
            }

class DashboardBuilder:
    """
    Helper class to build Grafana dashboard JSON
    """
    
    @staticmethod
    def generate_uid(query_data: Dict) -> str:
        """
        Generate unique dashboard UID from query data
        
        Args:
            query_data: Query information
        
        Returns:
            Dashboard UID
        """
        content = json.dumps(query_data, sort_keys=True)
        hash_val = hashlib.md5(content.encode()).hexdigest()[:8]
        return f"vizgenie-{hash_val}"
    
    
    @staticmethod
    def create_panel(
        panel_id: int,
        title: str,
        datasource_uid: str,
        datasource_type: str,
        query: str,
        query_type: str,
        x: int = 0,
        y: int = 0,
        width: int = 24,
        height: int = 12
    ) -> Dict:
        """
        Create a Grafana panel
        
        Args:
            panel_id: Panel ID
            title: Panel title
            datasource_uid: Datasource UID
            datasource_type: prometheus | postgres | loki
            query: Query string
            query_type: promql | sql | logql
            x, y, width, height: Grid position and size
        
        Returns:
            Panel JSON
        """
        # Determine panel type and format
        if query_type == 'promql':
            panel_type = 'timeseries'
            target_field = 'expr'
            format_type = 'time_series'
        elif query_type == 'sql':
            panel_type = 'table'
            target_field = 'rawSql'
            format_type = 'table'
        else:  # logql
            panel_type = 'logs'
            target_field = 'expr'
            format_type = 'logs'
        
        panel = {
            "id": panel_id,
            "type": panel_type,
            "title": title,
            "datasource": {
                "type": datasource_type,
                "uid": datasource_uid
            },
            "targets": [
                {
                    target_field: query,
                    "refId": "A",
                    "format": format_type
                }
            ],
            "gridPos": {
                "x": x,
                "y": y,
                "w": width,
                "h": height
            },
            "options": {},
            "fieldConfig": {
                "defaults": {
                    "unit": "short",
                    "decimals": 2
                },
                "overrides": []
            }
        }
        
        return panel
    
    
    @staticmethod
    def create_dashboard(
        uid: str,
        title: str,
        panels: list[Dict],
        tags: Optional[list[str]] = None
    ) -> Dict:
        """
        Create complete dashboard JSON
        
        Args:
            uid: Dashboard UID
            title: Dashboard title
            panels: List of panel objects
            tags: Optional tags
        
        Returns:
            Dashboard JSON
        """
        return {
            "uid": uid,
            "title": title,
            "tags": tags or ["vizgenie", "auto-generated"],
            "timezone": "browser",
            "schemaVersion": 36,
            "version": 0,
            "refresh": "30s",
            "panels": panels,
            "editable": True,
            "fiscalYearStartMonth": 0,
            "graphTooltip": 0,
            "links": [],
            "liveNow": False,
            "time": {
                "from": "now-6h",
                "to": "now"
            },
            "timepicker": {}
        }


# ===== TOOL FUNCTIONS (for LangGraph) =====

async def deploy_to_grafana(
    dashboard_json: Dict,
    grafana_url: str,
    grafana_api_key: str
) -> str:
    """
    LangGraph tool: Deploy dashboard to Grafana
    
    Args:
        dashboard_json: Dashboard JSON
        grafana_url: Grafana URL
        grafana_api_key: API key
    
    Returns:
        Dashboard URL
    """
    client = GrafanaClient(grafana_url, grafana_api_key)
    result = await client.create_dashboard(dashboard_json)
    
    if result.get('success'):
        return result['url']
    else:
        raise Exception(f"Dashboard deployment failed: {result.get('error')}")


async def fetch_grafana_datasources(
    grafana_url: str,
    grafana_api_key: str
) -> list[Dict]:
    """
    LangGraph tool: Fetch datasources from Grafana
    
    Args:
        grafana_url: Grafana URL
        grafana_api_key: API key
    
    Returns:
        List of datasources
    """
    client = GrafanaClient(grafana_url, grafana_api_key)
    return await client.fetch_datasources()


def build_dashboard_json(
    query_data: Dict,
    title: Optional[str] = None
) -> Dict:
    """
    LangGraph tool: Build dashboard JSON from query data
    
    Args:
        query_data: Query information
        title: Optional dashboard title
    
    Returns:
        Dashboard JSON
    """
    builder = DashboardBuilder()
    
    # Generate UID
    uid = builder.generate_uid(query_data)
    
    # Create panels
    panels = []
    result = query_data.get('result', [])
    
    for idx, item in enumerate(result):
        panel = builder.create_panel(
            panel_id=idx + 1,
            title=item.get('userquery', f'Panel {idx + 1}')[:50],
            datasource_uid=item.get('mandatory_datasource_uuid', ''),
            datasource_type=item.get('query_type', 'promql').replace('promql', 'prometheus').replace('sql', 'postgres'),
            query=item.get('query', ''),
            query_type=item.get('query_type', 'promql'),
            x=0,
            y=idx * 12,
            width=24,
            height=12
        )
        panels.append(panel)
    
    # Create dashboard
    dashboard_title = title or f"VizGenie Dashboard - {result[0].get('userquery', 'Auto-generated')[:30]}"
    
    dashboard = builder.create_dashboard(
        uid=uid,
        title=dashboard_title,
        panels=panels,
        tags=["vizgenie", "auto-generated"]
    )
    
    return dashboard